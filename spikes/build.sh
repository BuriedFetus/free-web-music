#!/usr/bin/env bash
# Build the spike DSP to WebAssembly and embed it for the test page.
# Needs: rustup target add wasm32-unknown-unknown
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
cargo build --release --target wasm32-unknown-unknown --manifest-path "$here/dsp/Cargo.toml"
wasm="$here/dsp/target/wasm32-unknown-unknown/release/fwm_dsp_spike.wasm"
cp "$wasm" "$here/dsp.wasm"
python3 - "$here/dsp.wasm" "$here/dsp-wasm.js" <<'PY'
import base64, sys
data = open(sys.argv[1], 'rb').read()
open(sys.argv[2], 'w').write('// generated by spikes/build.sh, do not edit\nwindow.DSP_WASM_B64 = "%s";\n' % base64.b64encode(data).decode())
print(f"dsp.wasm: {len(data)} bytes")
PY
